import test from 'node:test';
import assert from 'node:assert/strict';
import {normalizeGenericStatementHtml} from '../engine/generic-statement-tables.mjs';
import {combineIrReports} from '../engine/issuer-ir-tables-pilot.mjs';
const url='https://official.example.com/report/2025.html';
const row=(...cells)=>'<tr>'+cells.map(x=>'<td>'+x+'</td>').join('')+'</tr>';
const table=(...rows)=>'<table>'+rows.join('')+'</table>';
const header3=row('Years ended','September 27, 2025','September 28, 2024','September 30, 2023');
const header2=row('','September 27, 2025','September 28, 2024');
function appleStyle({omitTerm=false,ambiguous=false}={}){
 const income=table(header3,row('Net sales:'),row('Products','307,003','294,866','298,085'),
  row('Total net sales','416,161','','391,035','','383,285',''),
  row('Total cost of sales','220,960','210,352','214,137'),
  row('Operating income','133,050','123,216','114,301'),
  row('Net income','$','112,010','','','$','93,736','','','$','96,995'));
 const cash=table(header3,row('Operating activities:'),row('Net income','112,010','93,736','96,995'),
  row('Cash generated by operating activities','111,482','118,254','110,543'),
  row('Investing activities:'),row('Cash used in investing','(12,000)','(10,000)','(5,000)'));
 const balance=table(header2,row('ASSETS:'),row('Total assets','$','359,241','','','$','364,980'),
  row('Current liabilities:'),row('Commercial paper','7,979','9,967'),
  row('Term debt','12,350','10,912'),row('Total current liabilities','165,631','176,392'),
  row('Non-current liabilities:'),
  ...(omitTerm?[]:[row('Term debt','78,919','85,750')]),
  row('Total liabilities','285,508','308,030'));
 const segment=table(row('','2025','Change','2024','Change','2023'),
  row('Total net sales','$','416,161','6','%','$','391,035','2','%','383,285'));
 return '<html>'+segment+income+cash+balance+(ambiguous?income:'')+'</html>';
}
function msftStyle(){
 const income=table(row('Year Ended June 30','2025','2024','2023'),
  row('Total revenue','281,724','245,122','211,915'),
  row('Gross margin','193,893','171,008','146,052'),
  row('Net income','101,832','88,136','72,361'));
 const cash=table(row('Year Ended June 30','2025','2024','2023'),
  row('Net income','101,832','88,136','72,361'),
  row('Net cash from operations','136,162','118,548','87,582'),
  row('Net cash from investing activities','(45,000)','(25,000)','(10,000)'));
 const balance=table(row('June 30','2025','2024'),
  row('Total assets','619,003','512,163'),row('Current liabilities:'),
  row('Short-term debt','0','6,693'),
  row('Current portion of long-term debt','2,999','2,249'),
  row('Long-term debt','40,152','42,688'),
  row('Total liabilities','343,387','243,686'));
 return income+cash+balance;
}
test('generic statement extractor reads Apple-style full dates and split currency cells, without company aliases',()=>{
 const o=normalizeGenericStatementHtml(appleStyle(),{sourceUrl:url,reportYear:2025});
 assert.deepEqual(o.yearLists.income,[2025,2024,2023]);
 assert.deepEqual(o.statementSelection,{income:1,cash:2,balance:3});
 assert.equal(o.years[2025].revenue.value,416161000000);
 assert.equal(o.years[2024].netIncome.value,93736000000);
 assert.equal(o.years[2023].operatingCashflow.value,110543000000);
 assert.equal(o.years[2025].interestBearingDebt.value,99248000000);
 assert.equal(o.years[2024].interestBearingDebt.value,106629000000);
 assert.equal(o.years[2023].interestBearingDebt.status,'missing');
});
test('generic statement extractor also supports Microsoft-style HTML without regressing it',()=>{
 const o=normalizeGenericStatementHtml(msftStyle(),{sourceUrl:url,reportYear:2025});
 assert.equal(o.years[2025].revenue.value,281724000000);
 assert.equal(o.years[2024].operatingCashflow.value,118548000000);
 assert.equal(o.years[2025].interestBearingDebt.value,43151000000);
 assert.equal(o.years[2024].interestBearingDebt.value,51630000000);
});
test('missing line items and duplicate competing tables always fail closed',()=>{
 const incomplete=normalizeGenericStatementHtml(appleStyle({omitTerm:true}),{sourceUrl:url,reportYear:2025});
 assert.equal(incomplete.years[2025].interestBearingDebt.status,'missing');
 const conflict=normalizeGenericStatementHtml(appleStyle({ambiguous:true}),{sourceUrl:url,reportYear:2025});
 assert.equal(conflict.candidateCounts.income,2);
 assert.equal(conflict.years[2025].revenue.status,'missing');
});
test('currency symbols do not count as numbers; percentage/growth columns do not blend with fiscal values',()=>{
 const o=normalizeGenericStatementHtml(appleStyle(),{sourceUrl:url,reportYear:2025});
 assert.equal(o.years[2025].revenue.value,416161000000);
 assert.equal(o.years[2025].netIncome.value,112010000000);
 assert.equal(o.years[2025].netIncome.sourceTier,'issuer-html-not-xbrl');
});
test('generic parser restatement differences are detected via existing cross-report contract',()=>{
 const a=normalizeGenericStatementHtml(appleStyle(),{sourceUrl:url,reportYear:2025});
 const b=normalizeGenericStatementHtml(appleStyle().replace('111,482','111,982'),
  {sourceUrl:url.replace('2025.html','2024.html'),reportYear:2024});
 const c=combineIrReports([a,b]);
 assert.equal(c.years[2025].operatingCashflow.status,'conflict');
 assert.equal(c.years[2025].revenue.status,'ok');
});
