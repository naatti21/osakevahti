// Generic financial-statement HTML extraction – research only.
// Unlike a company-specific row matcher, this identifies statement purpose,
// dated columns, row meanings and debt sections. It fails closed on ambiguity.
// Source evidence is issuer HTML, NOT standardised/XBRL-verified facts.

const METRICS=['revenue','netIncome','operatingCashflow','interestBearingDebt'];
const MISSING=(reason,extra={})=>({status:'missing',reason,...extra});
const labelAliases={
 revenue:['total revenue','total net sales','total net revenues','net revenues'],
 netIncome:['net income','net income (loss)','profit for the year'],
 operatingCashflow:['net cash from operations','net cash provided by operating activities',
  'cash generated by operating activities','net cash provided by (used in) operating activities',
  'net cash generated by operating activities'],
 assets:['total assets'],liabilities:['total liabilities'],
 shortTermDebt:['short-term debt'],
 currentPortion:['current portion of long-term debt'],
 longTermDebt:['long-term debt'],
 commercialPaper:['commercial paper'],
 termDebt:['term debt']
};
// Labels are accounting terms, NOT issuer names or ticker-specific exceptions.
function decode(s){
 return String(s||'').replace(/&#x([0-9a-f]+);/gi,(_,h)=>String.fromCodePoint(parseInt(h,16)))
  .replace(/&#(\d+);/g,(_,n)=>String.fromCodePoint(Number(n)))
  .replace(/&(?:nbsp|ensp|emsp);/gi,' ').replace(/&amp;/gi,'&')
  .replace(/&(?:ndash|mdash);/gi,'—').replace(/&minus;/gi,'−');
}
function clean(s){return decode(String(s||'').replace(/<[^>]*>/g,' ')).replace(/\s+/g,' ').trim()}
function norm(s){return clean(s).toLowerCase().replace(/[.:]+$/,'').replace(/\s+/g,' ').trim()}
function match(s,aliases){return aliases.includes(norm(s))}
const toNumber=s=>{
 const x=clean(s);
 if(!/^\(?-?\$?\s*(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?\)?$/.test(x))return null;
 const n=Number(x.replace(/[\s$,()]/g,''));
 return Number.isFinite(n)?(x.startsWith('(')?-n:n):null;
};
function parseTables(html){
 if(typeof html!=='string'||html.length>20_000_000)throw new TypeError('HTML source missing or too large');
 return [...html.matchAll(/<table\b[^>]*>([\s\S]*?)<\/table>/gi)].map((m,index)=>{
  const rows=[...m[1].matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)]
   .map(x=>[...x[1].matchAll(/<t[dh]\b[^>]*>([\s\S]*?)<\/t[dh]>/gi)]
     .map(c=>clean(c[1]))).filter(x=>x.length>0);
  return {index,rows};
 });
}
function yearList(t){
 if(!t)return [];
 for(const cells of t.rows.slice(0,12)){
  if(cells.length<3)continue;
  const years=cells.slice(1).map(cell=>{
   if(!/^(?:(?:[a-z]+\s+\d{1,2},?\s+)?(?:19|20)\d{2}|(?:19|20)\d{2})$/i.test(cell))return null;
   const m=cell.match(/(19|20)\d{2}$/);return m?Number(m[0]):null;
  }).filter(y=>y>=2000&&y<=2100);
  if(years.length>=2&&years.length<=4&&new Set(years).size===years.length)return years;
 }
 return [];
}
function findRows(table,aliases){
 if(!table)return [];
 return table.rows.filter(x=>x.length&&match(x[0],aliases));
}
function count(t,aliases){return findRows(t,aliases).length}
function isCashStatement(t){
 return count(t,labelAliases.operatingCashflow)===1&&count(t,labelAliases.netIncome)>=1&&
  t.rows.some(r=>/(investing activities|financing activities|net cash used in investing)/i.test(r[0]||''));
}
function isIncomeStatement(t){
 return count(t,labelAliases.revenue)===1&&count(t,labelAliases.netIncome)===1&&
  t.rows.some(r=>/^(gross margin|gross profit|operating income|operating profit|total operating expenses)$/i.test(norm(r[0])));
}
function isBalanceSheet(t){
 return count(t,labelAliases.assets)===1&&count(t,labelAliases.liabilities)===1&&
  t.rows.some(r=>/current liabilities/i.test(r[0]||''));
}
function select(tables,kind){
 const predicate={income:isIncomeStatement,cash:isCashStatement,balance:isBalanceSheet}[kind];
 const matches=tables.filter(t=>yearList(t).length>=2&&predicate(t));
 // Do not pick a tempting narrative/segment or competing table automatically.
 return matches.length===1?{table:matches[0],candidates:1}:{table:null,candidates:matches.length};
}
function read(table,aliases,year,{unit,multiplier,sourceUrl}){
 if(!table)return MISSING('financial-statement-not-uniquely-identified');
 const years=yearList(table),position=years.indexOf(year);
 if(position<0)return MISSING('year-not-present-in-statement');
 const matching=findRows(table,aliases);
 if(matching.length!==1)return MISSING('row-missing-or-not-unique');
 const row=matching[0];
 // Standalone currency and punctuation cells are presentation tokens, never numbers.
 const numbers=row.slice(1).map(toNumber).filter(x=>x!==null);
 if(numbers.length!==years.length)return MISSING('numeric-columns-do-not-match-year-headings',
  {numericColumns:numbers.length,years});
 return {status:'ok',value:numbers[position]*multiplier,unit,
  fiscalYear:year,sourceUrl,sourceTier:'issuer-html-not-xbrl',
  concept:'HTML:'+norm(row[0]),tableIndex:table.index};
}
function sectionRow(t,label){
 const found=t.rows.findIndex(row=>norm(row[0])===norm(label));
 return found;
}
function accountingDebt(balance,year,opt){
 if(!balance)return MISSING('balance-sheet-not-uniquely-identified');
 const short=read(balance,labelAliases.shortTermDebt,year,opt);
 const current=read(balance,labelAliases.currentPortion,year,opt);
 const long=read(balance,labelAliases.longTermDebt,year,opt);
 if([short,current,long].every(x=>x.status==='ok'))
  return {status:'ok',value:short.value+current.value+long.value,
   unit:opt.unit,fiscalYear:year,sourceUrl:opt.sourceUrl,sourceTier:'issuer-html-not-xbrl',
   concept:'short-term debt + current portion of long-term debt + long-term debt'};
 // A second standard presentation splits commercial paper and term debt
 // across current vs non-current liability sections. Both sections and all
 // components must be explicit; never infer an absent component is zero.
 const currStart=sectionRow(balance,'Current liabilities:');
 const noncurrStart=sectionRow(balance,'Non-current liabilities:');
 if(currStart<0||noncurrStart<=currStart)return MISSING('debt-components-incomplete');
 const currentTable={...balance,rows:balance.rows.slice(currStart+1,noncurrStart)};
 const noncurrentTable={...balance,rows:balance.rows.slice(noncurrStart+1)};
 // Synthetic section retains the same parent table's year headings.
 const lookup=(part,aliases)=>{
  const augmented={...balance,rows:[...balance.rows.slice(0,12),...part.rows]};
  return read(augmented,aliases,year,opt);
 };
 const commercial=lookup(currentTable,labelAliases.commercialPaper);
 const termCurrent=lookup(currentTable,labelAliases.termDebt);
 const termLong=lookup(noncurrentTable,labelAliases.termDebt);
 if([commercial,termCurrent,termLong].every(x=>x.status==='ok')){
  return {status:'ok',value:commercial.value+termCurrent.value+termLong.value,
   unit:opt.unit,fiscalYear:year,sourceUrl:opt.sourceUrl,sourceTier:'issuer-html-not-xbrl',
   concept:'commercial paper + current term debt + non-current term debt',
   derivedFrom:[commercial.concept,termCurrent.concept,termLong.concept]};
 }
 return MISSING('debt-components-incomplete');
}
export function normalizeGenericStatementHtml(html,{sourceUrl,reportYear,years,
  currency='USD',multiplier=1_000_000}={}){
 if(!/^https:\/\/[a-z0-9.-]+\/[^\s]+$/i.test(sourceUrl||'')||
  !Number.isInteger(reportYear)||reportYear<2000||reportYear>2100||
  typeof multiplier!=='number'||!Number.isFinite(multiplier)||multiplier<=0||
  !/^[A-Z]{3}$/.test(currency))throw new TypeError('invalid-report-source-or-unit-metadata');
 const tables=parseTables(html);
 const income=select(tables,'income'),cash=select(tables,'cash'),balance=select(tables,'balance');
 const selections={income:income.table?.index??null,cash:cash.table?.index??null,
  balance:balance.table?.index??null};
 const opt={unit:currency,multiplier,sourceUrl},output={};
 for(const year of [...new Set(years||[reportYear,reportYear-1,reportYear-2])]){
  output[year]={
   revenue:read(income.table,labelAliases.revenue,year,opt),
   netIncome:read(income.table,labelAliases.netIncome,year,opt),
   operatingCashflow:read(cash.table,labelAliases.operatingCashflow,year,opt),
   interestBearingDebt:accountingDebt(balance.table,year,opt)
  };
 }
 return {provider:'Generic semantic statement HTML',reportYear,sourceUrl,years:output,
  sourceTier:'issuer-html-not-xbrl',quality:'research-only-no-independent-validation',
  statementSelection:selections,
  candidateCounts:{income:income.candidates,cash:cash.candidates,balance:balance.candidates},
  yearLists:{income:yearList(income.table),cash:yearList(cash.table),balance:yearList(balance.table)}};
}
export {METRICS as GENERIC_STATEMENT_METRICS};
